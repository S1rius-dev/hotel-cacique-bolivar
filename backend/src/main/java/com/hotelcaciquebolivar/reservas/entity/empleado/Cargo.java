/**
 * Enumeración que define los cargos disponibles para los empleados del hotel.
 */
public enum Cargo {
    /** Gerente del hotel con permisos de administración. */
    GERENTE,
    /** Recepcionista encargada de atención al cliente y gestión de reservas. */
    RECEPCIONISTA,
    /** Personal de limpieza encargado del mantenimiento de habitaciones. */
    LIMPIEZA
}
